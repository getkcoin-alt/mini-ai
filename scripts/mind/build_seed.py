#!/usr/bin/env python3
"""Generate the mind reference-data migration from taxonomy.json + adult stage files.

Writes supabase/migrations/20261110120100_mind_seed_v1.sql (idempotent upserts).
Run after build_taxonomy.py. `--check` fails if the SQL is out of date.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIND = ROOT / "services" / "mind"
OUT = ROOT / "supabase" / "migrations" / "20261110120100_mind_seed_v1.sql"


def q(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def arr(values, cast: str) -> str:
    return "ARRAY[" + ", ".join(q(v) for v in values) + f"]::{cast}[]" if values else f"'{{}}'::{cast}[]"


def build() -> str:
    t = json.loads((MIND / "taxonomy.json").read_text(encoding="utf-8"))
    adult = {s["stage"]: s for s in (json.loads(p.read_text(encoding="utf-8"))
                                     for p in sorted((MIND / "stages").glob("stage*.json")))}
    out = [f"-- GENERATED by scripts/mind/build_seed.py from services/mind (taxonomy {t['version']}). Do not edit.",
           "BEGIN;",
           f"INSERT INTO public.mind_taxonomy_versions(version, source) VALUES ({q(t['version'])}, {q(t['source'])}) ON CONFLICT (version) DO NOTHING;"]
    for g in t["groups"]:
        out.append("INSERT INTO public.mind_groups(id, title, meaning, intro, notes, default_level, ai_may_infer) VALUES "
                   f"({g['id']}, {q(g['title'])}, {q(g['meaning'])}, {q(g['intro'])}, {arr(g['notes'], 'text')}, "
                   f"{q(g['default_level'])}, {q(g['ai_may_infer'])}) ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, "
                   "meaning = EXCLUDED.meaning, intro = EXCLUDED.intro, notes = EXCLUDED.notes, "
                   "default_level = EXCLUDED.default_level, ai_may_infer = EXCLUDED.ai_may_infer;")
    rows = [f"({q(f['key'])}, {g['id']}, {q(f['label'])}, {q(f['optional'])}, {q(f['level'])}, {q(f['never_store'])}, "
            f"{q(f['ai_may_infer'])}, {q(f['data_type'])}, {arr(f.get('facets', []), 'text')})"
            for g in t["groups"] for f in g["fields"]]
    out.append("INSERT INTO public.mind_fields(key, group_id, label, optional, level, never_store, ai_may_infer, data_type, facets) VALUES\n  "
               + ",\n  ".join(rows) + "\nON CONFLICT (key) DO UPDATE SET group_id = EXCLUDED.group_id, label = EXCLUDED.label, "
               "optional = EXCLUDED.optional, level = EXCLUDED.level, never_store = EXCLUDED.never_store, "
               "ai_may_infer = EXCLUDED.ai_may_infer, data_type = EXCLUDED.data_type, facets = EXCLUDED.facets;")
    codes = {1: "childhood", 2: "adolescence"}
    for s in t["life_stages"]:
        a = adult.get(s["stage"])
        code = a["code"] if a else codes[s["stage"]]
        persona = json.dumps(a["persona"], ensure_ascii=False) if a else "{}"
        out.append("INSERT INTO public.mind_life_stages(stage, code, title, min_age, max_age, theme, persona, available) VALUES "
                   f"({s['stage']}, {q(code)}, {q(s['title'])}, {s['min_age']}, {q(s['max_age'])}, {q(s['theme'])}, "
                   f"{q(persona)}::jsonb, {q(bool(a))}) ON CONFLICT (stage) DO UPDATE SET code = EXCLUDED.code, title = EXCLUDED.title, "
                   "min_age = EXCLUDED.min_age, max_age = EXCLUDED.max_age, theme = EXCLUDED.theme, persona = EXCLUDED.persona, "
                   "available = EXCLUDED.available;")
        # children's stages: focus items from the doc are recorded, but no questions until Phase 6
        focus = a["focus"] if a else [{"item": item, "groups": [], "fields": [], "questions": [], "only_if_user_raises": True}
                                      for item in s["focus"]]
        for i, f in enumerate(focus, 1):
            fid = f"s{s['stage']}_{i:02d}"
            out.append("INSERT INTO public.mind_stage_focus(id, stage, ord, item, group_ids, field_keys, sensitive, only_if_user_raises, questions) VALUES "
                       f"({q(fid)}, {s['stage']}, {i}, {q(f['item'])}, {arr(f['groups'], 'smallint')}, {arr(f['fields'], 'text')}, "
                       f"{q(bool(f.get('sensitive')))}, {q(bool(f.get('only_if_user_raises')))}, {arr(f['questions'], 'text')}) "
                       "ON CONFLICT (id) DO UPDATE SET item = EXCLUDED.item, group_ids = EXCLUDED.group_ids, field_keys = EXCLUDED.field_keys, "
                       "sensitive = EXCLUDED.sensitive, only_if_user_raises = EXCLUDED.only_if_user_raises, questions = EXCLUDED.questions;")
    out.append("COMMIT;")
    return "\n".join(out) + "\n"


def main():
    sql = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != sql:
            sys.exit("mind seed migration is out of date: run scripts/mind/build_seed.py")
        print("seed up to date")
        return
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(sql.splitlines())} lines)")


if __name__ == "__main__":
    main()
